/**
 * Türen eines höheren Rangs aus Basiswerten auf E-Niveau ableiten.
 * HP und Schaden wachsen mit demselben Rangfaktor, der im Kampf auch den
 * eigenen Schaden anhebt – die Türen bleiben dadurch relativ gleich schwer,
 * während die absoluten Zahlen mitwachsen. Alles andere (Intervall,
 * Blockchance, Schwächen, Combo) bleibt unberührt.
 */
function skaliereTueren(rank, tueren) {
  const faktor = RANG_FAKTOR[rank] ?? 1
  return tueren.map((tuer) => ({
    ...tuer,
    hp: Math.round(tuer.hp * faktor),
    schaden: Math.round(tuer.schaden * faktor),
  }))
}


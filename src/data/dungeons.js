//   schwaechen   Schadensart → Multiplikator, z. B. { kraft: 2 }
//   resistenzen  Schadensart → Multiplikator, z. B. { core: 0.6 }
//   ausweichrate Chance, dass der Gegner ausweicht (foe.ev)
//   combo        Übungswechsel steigert deinen Schaden, Wiederholung bricht ihn
